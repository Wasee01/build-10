CREATE TABLE students (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);
CREATE TABLE sections (
    id BIGINT PRIMARY KEY,
    term_code VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    credit_hours INTEGER NOT NULL CHECK (credit_hours > 0),
    capacity INTEGER NOT NULL CHECK (capacity >= 0),
    registration_opens_at TIMESTAMP WITH TIME ZONE NOT NULL,
    registration_closes_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (registration_closes_at >= registration_opens_at)
);
CREATE TABLE enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    section_id BIGINT NOT NULL REFERENCES sections(id),
    status VARCHAR(255) NOT NULL CHECK (status IN ('ENROLLED', 'WAITLISTED')),
    UNIQUE (student_id, section_id)
);
CREATE INDEX ix_enrollment_section_status ON enrollments(section_id, status);
